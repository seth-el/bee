package bee

import (
	"net/url"
	"os"
	"os/user"
	"runtime"
	"strings"
)

const maxRuntimeFactBytes = 96

// HostRuntimeFacts describes the machine this Bee process runs on. It is read
// from the operating system once, at composition, so the model never has to
// infer its host from memory or notes, which go stale when Bee moves.
type HostRuntimeFacts struct {
	Hostname string
	Platform string
	User     string
}

// CurrentHostRuntimeFacts reads the host facts. Anything unavailable is left
// empty and omitted from the prompt.
func CurrentHostRuntimeFacts() HostRuntimeFacts {
	facts := HostRuntimeFacts{Platform: runtime.GOOS + "/" + runtime.GOARCH}
	if name, err := os.Hostname(); err == nil {
		facts.Hostname = sanitizeRuntimeFact(name)
	}
	if current, err := user.Current(); err == nil {
		facts.User = sanitizeRuntimeFact(current.Username)
	}
	return facts
}

// sanitizeRuntimeFact keeps a bounded, single-line, markup-free value.
func sanitizeRuntimeFact(value string) string {
	var builder strings.Builder
	for _, r := range strings.TrimSpace(value) {
		if r < 0x21 || r > 0x7e || r == '<' || r == '>' || r == '"' {
			continue
		}
		builder.WriteRune(r)
		if builder.Len() >= maxRuntimeFactBytes {
			break
		}
	}
	return builder.String()
}

// runtimeModelEndpoint returns the host[:port] of a provider URL, never its
// path, query or credentials.
func runtimeModelEndpoint(baseURL string) string {
	parsed, err := url.Parse(strings.TrimSpace(baseURL))
	if err != nil {
		return ""
	}
	return sanitizeRuntimeFact(parsed.Host)
}

// renderRuntimeContext renders the facts for one agent. The text depends only
// on the host and the configured model, so it is byte-stable across turns and
// sessions and does not disturb the provider prompt cache.
func renderRuntimeContext(facts HostRuntimeFacts, model, baseURL string) string {
	if facts.Hostname == "" {
		return ""
	}
	var builder strings.Builder
	builder.WriteString("host: ")
	builder.WriteString(facts.Hostname)
	if facts.Platform != "" {
		builder.WriteString(" (" + facts.Platform + ")")
	}
	if facts.User != "" {
		builder.WriteString("\nuser: " + facts.User)
	}
	if model = sanitizeRuntimeFact(model); model != "" {
		builder.WriteString("\nmodel: " + model)
		if endpoint := runtimeModelEndpoint(baseURL); endpoint != "" {
			builder.WriteString(", served from " + endpoint)
		}
	}
	return builder.String()
}

const runtimeContextCloseTag = "</bee-runtime>"

// appendRuntimeContext composes the runtime facts into the stable prefix.
func appendRuntimeContext(prompt, runtimeContext string) string {
	prompt = strings.TrimSpace(prompt)
	runtimeContext = strings.TrimSpace(runtimeContext)
	if prompt == "" || runtimeContext == "" {
		return prompt
	}
	return prompt + "\n\nThe following facts are generated by the Bee harness for this process. They are authoritative about where you are running right now: your tools (exec, files, terminal) act on this host unless a tool call names another one. Memory, notes and earlier conversation that place you on a different machine or model describe the past.\n<bee-runtime>\n" + runtimeContext + "\n" + runtimeContextCloseTag
}

// RuntimeFactsEnabled reports whether the runtime block is composed.
func (config AssistantConfig) RuntimeFactsEnabled() bool {
	return config.RuntimeFacts == nil || *config.RuntimeFacts
}

// runtimeContext renders this application's runtime facts for one agent.
func (app *Application) runtimeContext(model string) string {
	if app == nil || app.RuntimeFacts == nil {
		return ""
	}
	if strings.TrimSpace(model) == "" {
		model = app.Config.Provider.Model
	}
	return renderRuntimeContext(*app.RuntimeFacts, model, app.Config.Provider.BaseURL)
}
